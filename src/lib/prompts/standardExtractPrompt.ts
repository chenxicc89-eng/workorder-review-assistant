// ==========================================================================
// 规范抽取 Prompt —— 从「12345 常见回单模板/范例」反推出规范库条目
// --------------------------------------------------------------------------
// 输入:Word/Excel 模板解析出的纯文本(通常是"好回单的范例"或分类要求)。
// 任务:判断文本涉及几个工单类型,为每个类型反推出该类型回单应满足的
//       必备要素 / 规范要求 / 各级风险点,输出结构化 JSON(RuleStandard[])。
// 与 OCR 抽取同为"文本 → 结构化 JSON",走文本模型,不依赖视觉。
// ==========================================================================

export const STANDARD_EXTRACT_SYSTEM_PROMPT = `你是国家电网12345工单审核规范的整理助手。用户会给你一份「12345 常见诉求及对照模板」文档的文本(通常由 Word/Excel 解析而来)。
这类模板一般是一张对照表,每一行是一种诉求类型,常见列含义如下(列名或有出入,按语义理解):
- 诉求类型 / 市民常见诉求类型:该行对应的工单类型(如"突发故障停电""计划检修停电""办理业务类""拒绝换表")。
- 回单口径:合格回单应怎么写(范式表述)。
- 不计入材料口径 / 不计入评价事项清单:满足什么情形时,该问题【不予评价/不算问题】(即豁免情形)。
- 法律依据:支撑判定的法规条款(如《供电营业规则》第 X 条)。
- 佐证材料:一份合格回单应附的证明材料(如"现场抢修图片""停电信息截图")。

你的任务:把每一行整理成一条「回单审核规范」,供审核系统使用。字段映射:
1. orderType:该行的诉求类型,【照模板字面】即可,不要改写、不要强行套用其他类型名。
2. name:命名为"「诉求类型」回单规范"。
3. requiredItems(必备要素):合格回单必须包含的信息点 + 佐证材料列里要求的附件(如"现场抢修图片""业务支撑停电信息截图")。
4. standardRequirements(规范要求):回单口径、法律依据里体现的写法/依据要求(如"需说明与市民联系的时间、方式与核实过程";"依据《供电营业规则》第 X 条")。
5. learnedExemptions(豁免准则):把"不计入材料口径 / 不计入评价事项清单"整理成"当…情形时,不应报为问题"的句子(这是审核时的豁免尺度)。
6. highRiskIssues / mediumRiskIssues / lowRiskIssues:若模板体现了"缺了什么算严重问题",按重要性归入;模板没体现就留空数组,不要硬编。
7. standardOpinionTemplates(可选)、examples.good(可选):有明确范式/正例句就摘录(照抄不改写),没有就留空。

原则:
- 只依据文本内容整理,不编造模板中没有的内容。表述正式、简洁,每条独立可读。
- 把模板里的占位符(如"**月**日""***原因""xx业务")改写成通用表述,不要保留星号占位。
- 无法确定的地方写进 notes,不要硬凑。

只输出 JSON 对象,不要输出 Markdown 或解释。结构:
{
  "standards": [
    {
      "orderType": "诉求类型(照模板字面)",
      "name": "「诉求类型」回单规范",
      "requiredItems": string[],
      "standardRequirements": string[],
      "learnedExemptions": string[],
      "highRiskIssues": string[],
      "mediumRiskIssues": string[],
      "lowRiskIssues": string[],
      "standardOpinionTemplates": string[],
      "examples": { "good": string[] }
    }
  ],
  "notes": "不确定项说明(可空)",
  "confidence": 0.0~1.0
}`;

export function buildStandardExtractUserPrompt(
  orderTypes: readonly string[],
  text: string
): string {
  return `下面是从「12345 常见诉求及对照模板」文档解析出的文本。请把每一种诉求类型整理成一条回单审核规范,输出 JSON。

【已有工单类型(仅供参考;若模板类型与其中之一相同就复用该名称,否则照模板字面新建,不要强行套用)】
${orderTypes.join(" / ")}

【要求】
- 逐行/逐类型整理,一种诉求类型产出一条规范;模板有几种就产出几条。
- orderType 照模板字面(如"计划检修停电""办理业务类"),与上方已有类型同义时才复用其名称。
- "不计入材料口径 / 不计入评价事项清单"→ 整理进 learnedExemptions(豁免准则),写成"当…时不应报为问题"。
- 佐证材料列 → 并入 requiredItems;法律依据/回单口径 → 并入 standardRequirements。
- 占位符(**、***、xx)改写为通用表述,不保留星号。
- 各字段为字符串数组,无内容给空 []。
- 只返回 JSON 对象,字段见系统提示(standards / notes / confidence)。

【文档文本】
${text}`;
}
